function slugify(name: string): string {
  return (
    name
      .trim()
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/(^-|-$)/g, "") || "ostrix-site"
  );
}

function buildReadme(name: string, hasApiFiles: boolean): string {
  const apiNote = hasApiFiles
    ? `

## Backend functions (\`api/\`)

This project includes serverless functions in \`api/\` (contact form, booking, or newsletter handling).

- **Vercel** picks these up automatically — no config needed, each file in \`api/\` becomes a serverless endpoint at \`/api/<name>\`.
- **Netlify** doesn't use the \`api/\` convention directly — move these files into \`netlify/functions/\` and add a \`netlify.toml\` pointing \`functions\` at that folder (see https://docs.netlify.com/functions/overview/), or swap them for Netlify's serverless function format.
`
    : "";

  return `# ${name}

Generated by Ostrix.

## Run locally

\`\`\`bash
npm install
npm start
\`\`\`

This serves the static site locally (via the \`serve\` package) so you can preview it before deploying.

## Deploy anywhere

This is a plain static site (HTML/CSS/JS) — there's no build step. Deploy it to any static host:

### Vercel
\`\`\`bash
npm i -g vercel
vercel
\`\`\`

### Netlify
Drag this folder into https://app.netlify.com/drop, or:
\`\`\`bash
npm i -g netlify-cli
netlify deploy
\`\`\`

### Any other static host
Upload every file in this folder as-is.
${apiNote}`;
}

// Packages the site's files plus a generated package.json + README into one
// .zip — the site itself needs no build step, the package.json only exists
// to give the downloaded project a runnable local-preview command.
export async function downloadSiteZip(name: string, files: { path: string; content: string }[]): Promise<void> {
  const JSZip = (await import("jszip")).default;
  const zip = new JSZip();
  files.forEach((f) => zip.file(f.path, f.content));

  zip.file(
    "package.json",
    JSON.stringify(
      {
        name: slugify(name),
        version: "1.0.0",
        private: true,
        description: `${name} — generated by Ostrix`,
        scripts: { start: "npx serve ." },
        devDependencies: { serve: "^14.2.1" },
      },
      null,
      2
    )
  );
  zip.file("README.md", buildReadme(name, files.some((f) => f.path.startsWith("api/"))));

  const blob = await zip.generateAsync({ type: "blob" });
  const a = document.createElement("a");
  a.href = URL.createObjectURL(blob);
  a.download = `${slugify(name)}.zip`;
  a.click();
}
